set -eu

ARCH=$(uname -m)

echo "Installing build dependencies..."
echo "---------------------------------------------------------------"
pacman -Syu --noconfirm \
	alsa-lib          \
	cmake             \
	elfutils          \
	glib2             \
	glib2-devel       \
	graphene          \
	gtk4              \
	gtk4-layer-shell  \
	jdk8-openjdk      \
	jdk17-openjdk     \
	jq                \
	jre-openjdk       \
	libbsd            \
	libcap            \
	libglvnd          \
	libgudev          \
	libpng            \
	libportal         \
	libsndfile        \
	libunwind         \
	lz4               \
	meson             \
	openxr            \
	openssl           \
	pipewire-audio    \
	sdl2              \
	speech-dispatcher \
	sqlite            \
	valgrind          \
	vulkan-headers    \
	vulkan-icd-loader \
	wayland-protocols \
	webkitgtk-6.0     \
	xz                \
	zlib              \
	zip

echo "Installing debloated packages..."
echo "---------------------------------------------------------------"
get-debloated-pkgs --add-common --prefer-nano ffmpeg-mini

# the build needs java 8 to compile the old java code, make sure it
# is the java/javac that gets used during the builds
export JAVA_HOME=/usr/lib/jvm/java-8-openjdk
export PATH="$JAVA_HOME/bin:$PATH"
# some java tools run out of memory on low memory machines, especially
# dx when dexing the android core libraries, bump the default heap
export JAVA_TOOL_OPTIONS=-Xmx4096M

ATL_SOURCE=https://gitlab.com/android_translation_layer

build_meson_bin() (
	repo=$1
	shift

	echo "Building $ATL_SOURCE/$repo..."
	echo "---------------------------------------------------------------"
	git clone "$ATL_SOURCE/$repo" ./"$repo"
	cd ./"$repo"

	if [ "$repo" = 'android_translation_layer' ]; then
		# ATL.edge: build a chosen commit instead of master when ATL_REF is set
		if [ "${ATL_REF:-master}" != master ]; then
			git fetch origin "$ATL_REF"
			git checkout FETCH_HEAD
		fi
		# fix desktop entries generated by ATL: honour ATL_APP_LAUNCHER (the
		# AppImage path) instead of argv[0]. ATL.edge edits the call by pattern
		# rather than with pkgforge-dev's diff, which master outgrows (the
		# variable was renamed from desktop_entry to exec_cmd).
		sed -i 's|g_string_append_printf(\([a-z_]*\), "%s ", d->prgname);|{ const char *atl_app_launcher = getenv("ATL_APP_LAUNCHER"); g_string_append_printf(\1, "%s ", (atl_app_launcher \&\& *atl_app_launcher) ? atl_app_launcher : d->prgname); }|' \
			src/main-executable/main.c
		if ! grep -q ATL_APP_LAUNCHER src/main-executable/main.c; then
			echo "WARNING: could not apply the ATL_APP_LAUNCHER fix; desktop entries ATL creates will point at the AppImage mount"
		fi
		echo "$(git rev-parse --short HEAD)-edge" > ~/version
		# ATL's build-time tools (jni_upcall_gen) need Java 12+; its own
		# sources still target 1.8, so JDK 17 builds everything here
		export JAVA_HOME=/usr/lib/jvm/java-17-openjdk
		export PATH="$JAVA_HOME/bin:$PATH"
	fi

	meson setup build --prefix=/usr --libdir=lib --buildtype=release "$@"
	meson compile -C build
	meson install -C build
)

# wolfssl needs to be built with jni support enabled for art_standalone
build_wolfssl() (
	echo "Building wolfssl..."
	echo "---------------------------------------------------------------"
	curl -L -o wolfssl.tar.gz "https://github.com/wolfSSL/wolfssl/archive/refs/tags/v5.9.2-stable.tar.gz"
	tar -xzf wolfssl.tar.gz
	cd wolfssl-5.9.2-stable

	./autogen.sh

	./configure \
		--prefix=/usr                 \
		--libdir=/usr/lib             \
		--sysconfdir=/etc             \
		--mandir=/usr/share/man       \
		--localstatedir=/var          \
		--enable-shared               \
		--enable-static               \
		--enable-reproducible-build   \
		--disable-opensslall          \
		--disable-opensslextra        \
		--enable-aescbc-length-checks \
		--enable-curve25519           \
		--enable-ed25519              \
		--enable-ed25519-stream       \
		--disable-oldtls              \
		--enable-base64encode         \
		--enable-tlsx                 \
		--enable-scrypt               \
		--disable-examples            \
		--enable-keygen               \
		--enable-wolfssh              \
		--enable-jni

	make -j"$(nproc)"
	make install
)

# vixl is needed by art_standalone to build the aarch64 dex2oat code,
# on x86_64 it's not needed so we only build it there, see the atl aports
# recipe for how the aarch64 build provides it
build_vixl() (
	echo "Building vixl..."
	echo "---------------------------------------------------------------"
	curl -L -o vixl-7.0.0.tar.gz "https://github.com/Linaro/vixl/archive/refs/tags/7.0.0.tar.gz"
	tar -xzf vixl-7.0.0.tar.gz
	cd vixl-7.0.0

	patch -p1 < ../patches/vixl-meson-support.patch

	meson setup build --prefix=/usr --libdir=lib --buildtype=release -Dsimulator=none
	meson compile -C build
	meson install -C build
)

build_art_standalone() (
	echo "Building $ATL_SOURCE/art_standalone..."
	echo "---------------------------------------------------------------"
	git clone "$ATL_SOURCE/art_standalone" ./art_standalone
	cd ./art_standalone

	# make art resolve addr2line through PATH instead of the hardcoded /usr/bin/addr2line
	patch -p1 < ../patches/art-addr2line-path.patch
	# give dx more heap when dexing the core libraries
	patch -p1 < ../patches/art-dx-heap.patch
	# use the host's java cacerts instead of bundling a copy in the AppImage
	patch -p1 < ../patches/art-wolfssljni-host-cacerts.patch
	# fix sockets on hosts without ipv6: properly detect it and fall back
	# to ipv4, otherwise all sockets are created as AF_INET6 and fail with
	# EAFNOSUPPORT breaking internet
	patch -p1 < ../patches/art-ipv4-fixes.patch

	make ____PREFIX=/usr ____LIBDIR=lib -j"$(nproc)"
	make ____PREFIX=/usr ____INSTALL_ETC=/etc ____LIBDIR=lib install
)

# ATL.edge: ATL's tools/jni_upcall_gen needs asm, asm-tree and java-getopt at
# build time and finds them with Fedora's xmvn-resolve, which Arch lacks.
# Fetch pinned jars from Maven Central and pass their paths to meson instead.
TOOL_JARS="$PWD/tool-jars"
fetch_jar() (
	path=$1 sha256=$2
	mkdir -p "$TOOL_JARS"
	curl -fsSL -o "$TOOL_JARS/${path##*/}" "https://repo1.maven.org/maven2/$path"
	echo "$sha256  $TOOL_JARS/${path##*/}" | sha256sum -c -
)
fetch_jar org/ow2/asm/asm/9.8/asm-9.8.jar 876eab6a83daecad5ca67eb9fcabb063c97b5aeb8cf1fca7a989ecde17522051
fetch_jar org/ow2/asm/asm-tree/9.8/asm-tree-9.8.jar 14b7880cb7c85eed101e2710432fc3ffb83275532a6a894dc4c4095d49ad59f1
fetch_jar gnu/getopt/java-getopt/1.0.13/java-getopt-1.0.13.jar f09dc6369ffc4fe4362cbd49b6ac6c4a7471375ac5d884c71b0a625a889c38c4

# art_standalone requires wolfssl and bionic_translation
if [ "$ARCH" = 'aarch64' ]; then
	build_vixl
fi
build_wolfssl
build_meson_bin bionic_translation
build_art_standalone
build_meson_bin libopensles-standalone
build_meson_bin android_translation_layer \
	-Dasm_jar_path="$TOOL_JARS/asm-9.8.jar" \
	-Dasm_tree_jar_path="$TOOL_JARS/asm-tree-9.8.jar" \
	-Dgetopt_jar_path="$TOOL_JARS/java-getopt-1.0.13.jar"

# ATL.edge: record what was built, so check-update.sh can compare all four repos
mkdir -p ./dist
jq -n \
	--arg atl "$(git -C android_translation_layer rev-parse HEAD)" \
	--arg art "$(git -C art_standalone rev-parse HEAD)" \
	--arg bionic "$(git -C bionic_translation rev-parse HEAD)" \
	--arg opensles "$(git -C libopensles-standalone rev-parse HEAD)" \
	--arg version "$(cat ~/version)" \
	--arg built "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
	'{version: $version, atl: $atl, art_standalone: $art, bionic_translation: $bionic,
	  libopensles_standalone: $opensles, wolfssl: "v5.9.2-stable", builtAt: $built}' \
	> ./dist/atl-build.json

# java 8 is only needed to build, get rid of it so that the resulting
# AppImage does not bundle the wrong java runtime
pacman -Rns --noconfirm jdk8-openjdk jdk17-openjdk


